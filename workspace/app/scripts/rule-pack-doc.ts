import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { SBA_7A_PACK } from "../src/rules/sba7a";

/** Markdown description of the rule pack, generated from the code so the documentation cannot drift. */
export function renderRulePackDoc(): string {
  const p = SBA_7A_PACK;
  const rows = p.rules.map((r) => `| ${r.id} | ${r.title} | ${r.sop.section} | ${r.applies ? "conditional" : "always"} |`).join("\n");
  const gaps = p.notEvaluated.map((n) => `| ${n.item} | ${n.sop} | ${n.reason} |`).join("\n");
  return `# Rule pack: ${p.name} (${p.version}, effective ${p.effective})

Generated by \`npm run docs:rules\` from \`workspace/app/src/rules/sba7a.ts\`. Do not edit by hand; a test fails if this file is stale.
Every rule below cites the SBA SOP 50 10 section it implements. Rules are deterministic code; no model output is used in any rule.
Outcomes: pass, fail (definite), needs_review (a human must complete or confirm), not_applicable. A rule that cannot be evaluated never passes.
Rules read ACCEPTED facts only (see DECISIONS D-019), so a value that failed a validator or came from a flagged document cannot satisfy a rule.

## Implemented rules
| Id | What it checks | SOP section | Applies |
|---|---|---|---|
${rows}

## Lender policy inputs (not SBA rules)
The debt-service estimate uses an assumed note rate (placeholder 9 percent) supplied through \`LenderOverlay\`; it is printed in every result that uses it. It must be replaced by the lender's own pricing before any real use.

## Not evaluated (coverage gaps, reported with every run)
| Item | SOP section | Reason |
|---|---|---|
${gaps}

## Status
Rule logic was drafted from text parsed out of the SOP .docx (docs/SBA_PROCESS_MAP.md). Each rule needs a spot-check against the published SOP and a lender review before real use (BACKLOG B-111, B-115).
`;
}

if (process.argv[1]?.endsWith("rule-pack-doc.ts")) {
  writeFileSync(join(import.meta.dirname, "..", "..", "docs", "RULE_PACK.md"), renderRulePackDoc());
  console.log("wrote workspace/docs/RULE_PACK.md");
}
